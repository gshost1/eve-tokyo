#!/usr/bin/env bash
# Pinned eve checkout with the eve-tokyo bench copied in. Re-run after editing bench/src.
# EVE_SHA picks the eve commit. The published results used 0fd4240d31c0fdf18e61dfdedf3c203eb595bba2
# (eve 0.79.0); the default is the merge of #4773, which also contains #4771.
set -euo pipefail
EVE_SHA="${EVE_SHA:-a3654ef7e8fc193d128f6523ba915d476857589e}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
EVE="$ROOT/.cache/eve"
if [ ! -d "$EVE/.git" ]; then
  git init -q "$EVE"
  git -C "$EVE" remote add origin https://github.com/vercel/eve.git
fi
if [ "$(git -C "$EVE" rev-parse HEAD 2>/dev/null || true)" != "$EVE_SHA" ]; then
  git -C "$EVE" fetch -q --depth 1 origin "$EVE_SHA"
  git -C "$EVE" checkout -q -f FETCH_HEAD
  (cd "$EVE" && pnpm install --frozen-lockfile --ignore-scripts --filter eve... >/dev/null)
fi
COMP="$EVE/packages/eve/src/harness/compaction"
DEST="$EVE/packages/eve/src/eve-tokyo"
# Variants and probe copies from an earlier setup are untracked files in eve's compaction folder.
git -C "$EVE" clean -fdq -- packages/eve/src/harness/compaction
rm -rf "$DEST" && mkdir -p "$DEST"
cp "$ROOT"/bench/src/*.ts "$DEST/"
cp "$ROOT/bench/vitest.bench.config.ts" "$EVE/packages/eve/"
# Strategy variants: sibling copies of the real engine/prompt with one patch each, from the patch
# set written for this eve commit (bench/patches/<first 7 of EVE_SHA>/). See bench/patches/README.md.
PATCHES="$ROOT/bench/patches/${EVE_SHA:0:7}"
DEFAULT_LABEL="eve-default"
[ -f "$PATCHES/DEFAULT_LABEL" ] && DEFAULT_LABEL="$(tr -d '[:space:]' < "$PATCHES/DEFAULT_LABEL")"
STRATS="$DEST/strategies.ts"
{
  echo "// Generated by bench/setup.sh for eve $EVE_SHA. Do not edit; edit bench/patches instead."
  echo 'import * as eveDefault from "#harness/compaction/engine.js";'
  echo
  echo 'import type { Engine } from "./replay.js";'
  echo
  echo "export const EVE_SHA = \"$EVE_SHA\";"
  echo "export const STRATEGIES: Record<string, Engine> = { \"$DEFAULT_LABEL\": eveDefault };"
} > "$STRATS"
for p in "$PATCHES"/*.patch; do
  [ -e "$p" ] || continue
  name="$(basename "$p" .patch)"
  label="$(sed -n '1s/^label: //p' "$p")"
  label="${label:-$name}"
  work="$(mktemp -d)"
  cp "$COMP/engine.ts" "$COMP/prompt.ts" "$work/"
  (cd "$work" && patch -s -p1 < "$p")
  sed "s#\"\#harness/compaction/prompt.js\"#\"\#harness/compaction/prompt.$name.js\"#" "$work/engine.ts" > "$COMP/engine.$name.ts"
  cp "$work/prompt.ts" "$COMP/prompt.$name.ts"
  rm -rf "$work"
  {
    echo "import * as v_$name from \"#harness/compaction/engine.$name.js\";"
    echo "STRATEGIES[\"$label\"] = v_$name;"
  } >> "$STRATS"
done
echo "eve at $EVE_SHA, bench in $DEST, strategies: $(grep -oE 'STRATEGIES\[\"[^\"]+\"\]|\"[^\"]+\": eveDefault' "$STRATS" | grep -oE '\"[^\"]+\"' | tr '\n' ' ')"
